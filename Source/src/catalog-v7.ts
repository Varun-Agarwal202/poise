// Frozen interleaving: every sixteen-day window uses each family once. Slot
// categories rotate, so the first object isn't always the same kind of object.
const ORDERS = [7, 0, 11, 4, 14, 2, 9, 15, 5, 12, 1, 8, 3, 13, 6, 10];
export function novelFamilies(day: number) {
  return Array.from({ length: 5 }, (_, slot) => {
    const group = (slot + day) % 5;
    return NOVEL_GROUPS[group][ORDERS[(day + [0, 3, 0, 9, 12][group]) % 16]];
  });
}

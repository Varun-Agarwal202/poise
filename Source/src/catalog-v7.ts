type Ink = 0 | 1 | 2 | "X";
const P = (m: Ink, ...xy: number[]): Part => [
  String(m),
  "p",
  ...xy.map((v) => v / 100),
];
const O = (m: Ink, x: number, y: number, w: number, h: number): Part => [
  String(m),
  "b",
  ...Array.from({ length: 32 }, (_, i) => [
    (x + Math.cos((i * Math.PI) / 16) * w) / 100,
    (y + Math.sin((i * Math.PI) / 16) * h) / 100,
  ]).flat(),
];
const B = (
  m: Ink,
  x: number,
  y: number,
  X: number,
  Y: number,
  w: number,
): Part => {
  const L = Math.hypot(X - x, Y - y),
    dx = ((-(Y - y) / L) * w) / 2,
    dy = (((X - x) / L) * w) / 2;
  return P(m, x + dx, y + dy, X + dx, Y + dy, X - dx, Y - dy, x - dx, y - dy);
};
const R = (m: Ink, x: number, y: number, w: number, h: number) =>
  P(m, x, y, x + w, y, x + w, y + h, x, y + h);
type Art = { name: string; parts: Part[] };
const A: Record<string, Art> = {};
const add = (id: string, name: string, ...parts: Part[]) => {
  A[id] = { name, parts };
};

